// Real local API/UI checks; no intercepted responses or simulated generations.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const base = process.env.AFS_UI_TEST_URL || 'http://127.0.0.1:8766';
const emptyBase = process.env.AFS_UI_EMPTY_URL;
const evidence = path.resolve('docs/evidence');
fs.mkdirSync(evidence, {recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1600,height:1050}});
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const checks=[];
try {
  await page.goto(base+'/#create');
  await page.getByRole('combobox',{name:'View camera',exact:true}).waitFor();
  const camera = page.getByRole('combobox',{name:'View camera',exact:true});
  await camera.focus(); await page.keyboard.press('Enter');
  await page.getByRole('listbox').waitFor();
  await page.keyboard.press('End'); await page.keyboard.press('Enter');
  await page.getByRole('combobox',{name:'View camera',exact:true}).filter({hasText:'gameplay'}).waitFor();
  assert.equal(await page.getByRole('listbox').count(),0); checks.push('Custom select End/Enter updates real React-controlled value');
  await camera.press('Enter'); await page.keyboard.press('Home'); await page.keyboard.press('Enter');
  await camera.filter({hasText:'three quarter'}).waitFor(); checks.push('Home selects first option');
  await camera.focus(); await page.keyboard.type('back'); await page.keyboard.press('Enter');
  await camera.filter({hasText:'back'}).waitFor(); checks.push('Typeahead selects matching option');
  await camera.click(); await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('listbox').count(),0);
  assert(await camera.evaluate(el=>el===document.activeElement)); checks.push('Escape closes popup and keeps focus');
  await camera.click(); await page.locator('.breadcrumb').click();
  assert.equal(await page.getByRole('listbox').count(),0); checks.push('Outside click dismisses popup');
  assert.equal(await page.locator('#project-switcher').getAttribute('aria-hidden'),'true');
  assert.equal(await page.locator('#project-switcher').getAttribute('tabindex'),'-1');
  assert(await page.locator('#project-switcher').inputValue()); checks.push('Stable project switcher value retained with hidden native semantics');
  await page.locator('.viewer-loading').waitFor({state:'hidden',timeout:180000});
  await camera.click();
  await page.screenshot({path:path.join(evidence,'ui_refinement_create.png'),fullPage:true,animations:"disabled"});
  await page.keyboard.press('Escape');
  await page.getByRole('link',{name:'Library',exact:true}).click();
  await page.locator('.library-toolbar').waitFor();
  await page.screenshot({path:path.join(evidence,'ui_refinement_library.png'),fullPage:true,animations:'disabled'});
  await page.getByRole('link',{name:'Create',exact:true}).click();
  await camera.waitFor();
  await page.getByRole('link',{name:'Home',exact:true}).click();
  await page.locator('.home-hero').waitFor();
  await page.screenshot({path:path.join(evidence,'ui_refinement_home.png'),fullPage:true,animations:"disabled"});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('link',{name:'Create',exact:true}).click(); await camera.waitFor(); await camera.click();
  assert.equal(await page.getByRole('listbox').evaluate(el=>getComputedStyle(el).animationName),'none'); checks.push('Reduced-motion disables popup animations');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:900,height:1000});
  await page.screenshot({path:path.join(evidence,'ui_refinement_tablet.png'),fullPage:true,animations:"disabled"});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)); checks.push('900px tablet has no page overflow');
  if(emptyBase) {
    const fresh=await browser.newPage({viewport:{width:1440,height:1000}});
    await fresh.goto(emptyBase+'/#home');
    await fresh.getByRole('button',{name:'Create your first project',exact:true}).waitFor();
    await fresh.screenshot({path:path.join(evidence,'ui_refinement_empty.png'),fullPage:true,animations:"disabled"});
    const before=await (await fresh.request.get(emptyBase+'/api/projects')).json(); assert.equal(before.length,0);
    await fresh.getByRole('link',{name:'Create',exact:true}).click();
    assert.equal(await fresh.getByRole('button',{name:/Generate 3D/}).count(),0);
    await fresh.getByRole('button',{name:'Create your first project',exact:true}).click();
    await fresh.getByRole('textbox',{name:'Project name',exact:true}).fill('UI Refinement QA');
    await fresh.getByRole('button',{name:'Save project',exact:true}).click();
    await fresh.getByRole('dialog').waitFor({state:'hidden'});
    await fresh.getByRole('combobox',{name:'Engine',exact:true}).waitFor();
    const projects=await (await fresh.request.get(emptyBase+'/api/projects')).json();assert.equal(projects.length,1);
    const snapshot=await (await fresh.request.get(emptyBase+'/api/studio?project_id='+projects[0].id)).json();
    assert.equal(snapshot.assets.length,0);assert.equal(snapshot.jobs.length,0);
    await fresh.reload(); await fresh.getByRole('combobox',{name:'Engine',exact:true}).waitFor();
    assert.equal(await fresh.locator('#project-switcher').inputValue(),projects[0].id);
    checks.push('Fresh empty library → create actual project → zero assets/jobs → refresh retains project');
    await fresh.getByRole('link',{name:'Settings',exact:true}).click();
    await fresh.getByRole('button',{name:'Edit project',exact:true}).click();
    const units=fresh.getByRole('combobox',{name:'Project units',exact:true}); await units.waitFor();
    await units.click(); await fresh.keyboard.press('Escape');
    assert.equal(await fresh.getByRole('dialog').count(),1); checks.push('Escape closes custom select before modal');
    await fresh.getByRole('button',{name:'Close dialog',exact:true}).click();
    await fresh.close();
  }
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(evidence,'ui_refinement.json'),JSON.stringify({status:'PASS',checks,errors,real_backend:base,empty_backend:emptyBase||'NOT_TESTED',scope:'UI controls and actual project persistence; no AI generation enqueued'},null,2)+'\n');
  console.log(JSON.stringify({status:'PASS',checks}));
} finally { await browser.close(); }
