import {test, expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('project isolation, library persistence and actual QA GLB viewer/export', async ({page, request, baseURL}) => {
  // Separate QA server/database. These are actual box bytes, never AI quality evidence.
  expect(baseURL).toContain(':8767');
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#home');
  await page.getByRole('button', {name:'New project',exact:true}).click();
  const name = 'UI QA game ' + Date.now();
  await page.getByLabel('Project name',{exact:true}).fill(name);
  await page.getByRole('button',{name:'Save project',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const projects = await (await request.get('/api/projects')).json();
  const project = projects.find((p: {name:string}) => p.name === name);
  expect(project).toBeTruthy();
  const empty = await (await request.get(`/api/studio?project_id=${project.id}`)).json();
  expect(empty.assets).toEqual([]); expect(empty.artifacts).toEqual([]); expect(empty.jobs).toEqual([]);
  await page.getByRole('link',{name:'Create',exact:true}).click();
  await page.getByRole('tab',{name:'Text',exact:true}).click();
  await expect(page.getByRole('button',{name:'Generate 3D',exact:true})).toBeDisabled();
  await page.getByRole('tab',{name:'Text + Image',exact:true}).click();
  await page.getByLabel('Asset name',{exact:true}).fill('QA BOX / NOT AI');
  await page.getByLabel('Describe your asset').fill('QA geometry fixture; not a generation or Meshy reference.');
  await page.getByRole('button',{name:'Save draft to library',exact:true}).click();
  let snapshot = await (await request.get(`/api/studio?project_id=${project.id}`)).json();
  const asset = snapshot.assets[0]; expect(asset.name).toBe('QA BOX / NOT AI');
  const report = JSON.parse(fs.readFileSync(path.resolve('../../docs/evidence/blender_smoke.json'),'utf8'));
  const raw = fs.readFileSync(path.join(report.run_path,'output/LOD0.glb'));
  const imported = await request.post(`/api/import/candidate?project_id=${project.id}&asset_id=${asset.id}`, {
    multipart:{file:{name:'qa_box_not_ai.glb',mimeType:'model/gltf-binary',buffer:raw}}
  }); expect(imported.ok()).toBeTruthy();
  await page.reload();
  await page.getByRole('link',{name:'Library',exact:true}).click();
  await page.getByRole('button',{name:'QA BOX / NOT AI',exact:true}).click();
  await expect(page.locator('.viewer')).toHaveAttribute('data-loaded','1',{timeout:45000});
  await page.getByLabel('View camera').selectOption('bottom');
  await page.getByRole('button',{name:'Clay',exact:true}).click();
  await page.getByRole('button',{name:'Normals',exact:true}).click();
  await page.getByRole('button',{name:'Wire',exact:true}).click();
  await page.getByRole('button',{name:/^(PBR|Textured)$/}).click();
  await page.getByRole('button',{name:/^Approve master$/i}).click();
  await page.getByLabel('Reviewer',{exact:true}).fill('QA fixture only');
  await page.getByRole('button',{name:'Approve this master',exact:true}).click();
  await page.getByRole('button',{name:'Export',exact:true}).click();
  await page.getByRole('button',{name:'Prepare export',exact:true}).click();
  await expect(page.getByRole('dialog').locator('.export-files a').first()).toBeVisible();
  const url = await page.getByRole('dialog').locator('.export-files a').first().getAttribute('href');
  expect((await (await request.get(url!)).body()).subarray(0,4).toString()).toBe('glTF');
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.reload();
  await expect(page.locator('.viewer')).toHaveAttribute('data-loaded','1',{timeout:45000});
  expect(await page.getByLabel('Describe your asset').inputValue()).toContain('QA geometry fixture');
  snapshot = await (await request.get(`/api/studio?project_id=${project.id}`)).json();
  expect(snapshot.assets[0].master_artifact_id).toBeTruthy();
  expect(snapshot.assets[0].exports).toHaveLength(1);
  const runavelle = await (await request.get('/api/studio?project_id=runavelle')).json();
  expect(runavelle.assets.some((a:{id:string})=>a.id===asset.id)).toBeFalsy();
  await page.keyboard.press('Control+s');
  await expect(page.getByRole('status')).toContainText('Draft saved locally');
  await page.keyboard.press('Alt+3');
  await expect(page).toHaveURL(/#library$/);
  expect(errors).toEqual([]);
});
